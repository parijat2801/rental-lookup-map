var WELCOME_RAMP = " .:-=+*#%@";
var WELCOME_BAYER = [0, 8, 2, 10, 12, 4, 14, 6, 3, 11, 1, 9, 15, 7, 13, 5];
var welcomePhotoPx = null;
var welcomeResizeBound = false;
function welcomeGridSize() {
    var probe = byId("welcome-ascii");
    var sample = document.createElement("span");
    sample.textContent = "M";
    probe.appendChild(sample);
    var rect = sample.getBoundingClientRect();
    sample.remove();
    var charW = rect.width || 3.6;
    var charH = rect.height || 6;
    var box = probe.getBoundingClientRect();
    return {
        cols: Math.max(24, Math.floor((box.width || 480) / charW)),
        rows: Math.max(12, Math.floor((box.height || 140) / charH)),
        charW: charW,
        charH: charH,
    };
}
function welcomePhoto() {
    if (welcomePhotoPx) return welcomePhotoPx;
    var bin = atob(WELCOME_PHOTO);
    var px = new Uint8Array(bin.length);
    for (var i = 0; i < bin.length; i++) px[i] = bin.charCodeAt(i);
    welcomePhotoPx = px;
    return px;
}
function paintWelcomeAscii() {
    var size = welcomeGridSize();
    var cols = size.cols;
    var rows = size.rows;
    var src = welcomePhoto();
    var sw = WELCOME_PHOTO_W;
    var sh = WELCOME_PHOTO_H;
    var aspect = size.charW / size.charH;
    var scale = Math.min((cols * aspect) / sw, rows / sh);
    var drawC = Math.min(cols, Math.max(1, Math.round((sw * scale) / aspect)));
    var drawR = Math.min(rows, Math.max(1, Math.round(sh * scale)));
    var ox = Math.floor((cols - drawC) / 2);
    var oy = Math.floor((rows - drawR) / 2);
    var ramp = WELCOME_RAMP;
    var levels = ramp.length - 1;
    var lines = new Array(rows);
    for (var y = 0; y < rows; y++) {
        var row = "";
        var sy = -1;
        if (y >= oy && y < oy + drawR)
            sy = Math.min(sh - 1, Math.floor(((y - oy + 0.5) * sh) / drawR));
        for (var x = 0; x < cols; x++) {
            var level = 0;
            if (sy >= 0 && x >= ox && x < ox + drawC) {
                var sx = Math.min(sw - 1, Math.floor(((x - ox + 0.5) * sw) / drawC));
                level = src[sy * sw + sx] / 255;
            }
            var q = Math.floor(level * levels);
            var threshold = (WELCOME_BAYER[(y % 4) * 4 + (x % 4)] + 0.5) / 16;
            if (level * levels - q > threshold && q < levels) q++;
            row += ramp.charAt(q);
        }
        lines[y] = row;
    }
    byId("welcome-ascii").textContent = lines.join("\n");
}
function stopWelcomeAscii() {}
function freezeWelcomeAscii() {}
function startWelcomeAscii() {
    paintWelcomeAscii();
    requestAnimationFrame(function () {
        if (welcomeStep === "title") paintWelcomeAscii();
    });
    if (!welcomeResizeBound) {
        welcomeResizeBound = true;
        window.addEventListener("resize", function () {
            var overlay = byId("welcome-overlay");
            if (!overlay || overlay.hidden || welcomeStep !== "title") return;
            paintWelcomeAscii();
        });
    }
}
